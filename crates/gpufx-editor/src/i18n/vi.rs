//! Vietnamese strings. No `_` arm: a new message must be given text here.

use super::{ClipAction, ClipEdge, Message, StreamKind, TrackLabel};

fn stream_name(stream: StreamKind) -> &'static str {
    match stream {
        StreamKind::Video => "video",
        StreamKind::Audio => "âm thanh",
    }
}

fn track_label(track: TrackLabel) -> String {
    match track {
        TrackLabel::Video(number) => format!("Track video {number}"),
        TrackLabel::Audio(number) => format!("Track âm thanh {number}"),
        TrackLabel::Position(number) => format!("Track {number}"),
    }
}

fn select_clip(action: ClipAction) -> &'static str {
    match action {
        ClipAction::Split => "Hãy chọn một clip để tách",
        ClipAction::Delete => "Hãy chọn một clip để xóa",
        ClipAction::Change => "Hãy chọn một clip để thay đổi",
        ClipAction::Mute => "Hãy chọn một clip để tắt tiếng",
        ClipAction::Trim => "Hãy chọn một clip để cắt bớt",
        ClipAction::AddEffect => "Hãy chọn một clip để thêm hiệu ứng",
        ClipAction::RemoveEffect => "Hãy chọn một clip để xóa hiệu ứng",
        ClipAction::AddTransition => "Hãy chọn một clip để thêm chuyển cảnh",
    }
}

